def print_banner(min_width: int = 100) -> bool:
    """Print the banner. Falls back to a compact header if the terminal
    is narrower than min_width (banner is 100 cols and would wrap)."""
    try:
        import shutil
        cols = shutil.get_terminal_size(fallback=(120, 24)).columns
    except Exception:
        cols = 120
    if cols >= min_width:
        print(BANNER)
    else:
        print("=" * min(60, cols))
        print("  DECEPTRON")
        print("=" * min(60, cols))
    print(f"  {TAGLINE}")
    print(f"  {AUTHOR}")
    print()
    return cols >= min_width


